"""Generate ``docs/CYPHER.md`` from ``graph/queries.py``.

> Implements P1-A-09. Walks every function in :mod:`graph.queries`, reads
> its docstring (Purpose / Tool / Demo question sections), and writes a
> Markdown document that lists every Cypher query the product depends
> on with purpose, tool, and demo question.
"""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

from graph.queries import QUERY_REGISTRY

_REPO_ROOT = Path(__file__).resolve().parent.parent


def _format_doc(name: str, fn) -> str:
    doc = inspect.getdoc(fn) or "(no docstring)"
    return f"## `{name}`\n\n{doc}\n"


def main() -> int:
    parts: list[str] = []
    parts.append("# OrgMind Cypher Reference\n")
    parts.append(
        "This document is generated by `scripts/export_cypher_doc.py` from "
        "`graph/queries.py`. Every function below is a named, parameterised "
        "Cypher query. The docstring's `Purpose`, `Tool`, and `Demo question` "
        "sections are how the eval runner and the docs stay aligned.\n"
    )
    for name in sorted(QUERY_REGISTRY):
        parts.append(_format_doc(name, QUERY_REGISTRY[name]))

    out_path = _REPO_ROOT / "docs" / "CYPHER.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print(f"Wrote {out_path} ({len(QUERY_REGISTRY)} queries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())